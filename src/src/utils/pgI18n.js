let override = null;

export function pgSetLang(lang) {
  override = lang === 'en' || lang === 'tr' ? lang : null;
  try {
    if (override) localStorage.setItem('pgx_ui_lang', override);
  } catch {
    /* storage disabled */
  }
}

export function pgLang() {
  if (override) return override;
  if (typeof window !== 'undefined' && window.pixelglobe && window.pixelglobe.lang) {
    return window.pixelglobe.lang === 'en' ? 'en' : 'tr';
  }
  try {
    const stored = localStorage.getItem('pgx_ui_lang');
    if (stored === 'en' || stored === 'tr') return stored;
  } catch {
    /* storage disabled */
  }
  if (typeof navigator !== 'undefined' && navigator.language) {
    return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
  }
  return 'tr';
}

export function pgT(key, vars) {
  const table = DICT[pgLang()] || DICT.tr;
  let out = table[key] || DICT.tr[key] || key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      out = out.replace(new RegExp(`\\{${name}\\}`, 'g'), vars[name]);
    });
  }
  return out;
}

export default pgT;
